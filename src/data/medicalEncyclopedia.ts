export function searchMedicalTopics(
  query: string,
  specialtyId = 'all'
): MedicalEncyclopediaTopic[] {
  const normQuery = (query || '').trim().toLowerCase();
  return MEDICAL_ENCYCLOPEDIA_TOPICS.filter((topic) => {
    const matchesSpecialty = specialtyId === 'all' || topic.specialtyId === specialtyId;
    if (!matchesSpecialty) return false;
    if (!normQuery) return true;
    const haystack = [
      topic.title,
      topic.subtitle,
      topic.overview,
      ...topic.symptoms,
      ...topic.causesAndRiskFactors,
      ...topic.treatmentAndSelfCare,
      ...topic.keywords,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(normQuery);
  });
}

