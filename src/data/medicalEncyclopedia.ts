export const MEDICAL_PROFILE_LOCAL_STORAGE_KEY = 'qais_user_medical_profile_v1';

export function loadLocalMedicalProfile(): UserMedicalProfile {
  if (typeof window === 'undefined') return DEFAULT_USER_MEDICAL_PROFILE;
  try {
    const raw = window.localStorage.getItem(MEDICAL_PROFILE_LOCAL_STORAGE_KEY);
    if (!raw) return DEFAULT_USER_MEDICAL_PROFILE;
    const parsed = JSON.parse(raw);
    return {
      ...DEFAULT_USER_MEDICAL_PROFILE,
      ...parsed,
      allergies: Array.isArray(parsed?.allergies) ? parsed.allergies : [],
      chronicConditions: Array.isArray(parsed?.chronicConditions) ? parsed.chronicConditions : [],
      currentMedications: Array.isArray(parsed?.currentMedications) ? parsed.currentMedications : [],
      pastSurgeries: Array.isArray(parsed?.pastSurgeries) ? parsed.pastSurgeries : [],
      familyHistory: Array.isArray(parsed?.familyHistory) ? parsed.familyHistory : [],
    };
  } catch {
    return DEFAULT_USER_MEDICAL_PROFILE;
  }
}

export function saveLocalMedicalProfile(profile: UserMedicalProfile): UserMedicalProfile {
  const updated: UserMedicalProfile = {
    ...profile,
    updatedAt: new Date().toISOString(),
  };
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(MEDICAL_PROFILE_LOCAL_STORAGE_KEY, JSON.stringify(updated));
    } catch {
      // ignore storage quota errors
    }
  }
  return updated;
}

