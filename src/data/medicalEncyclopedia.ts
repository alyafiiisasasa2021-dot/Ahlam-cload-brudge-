  /طبي|طبية|دكتور|علاج|دواء|أدوية|ادوية|مرض|اعراض|أعراض|تشخيص|تحليل|تحاليل|ضغط|سكر|سكري|انسولين|إنسولين|تراكمي|كوليسترول|قلب|شرايين|خفقان|صداع|شقيقة|اعصاب|أعصاب|دوخة|ربو|كحة|سعال|تنفس|صدر|معدة|قولون|حموضة|ارتجاع|جرثومة|كبد|عظام|مفاصل|ظهر|غضروف|عرق النسا|نقرس|هشاشة|كلى|حصوات|مسالك|بول|فقر دم|انيميا|أنيميا|حديد|فيتامين|حامل|حمل|اطفال|أطفال|حمى|حرارة|اسنان|أسنان|ضرس|لثة|تسوس|عصب السن|تقويم|خراج|تخدير|قلع|حشوة|اموكسيسيلين|مضاد حيوي|مسكن|ارق|أرق|توتر|قلق|نوم|إسعاف|اسعاف|حروق|نزيف|هبوط/i;

export function isMedicalOrHealthQuery(text: string): boolean {
  const q = (text || '').trim();
  if (!q) return false;
  if (MEDICAL_DETECTION_REGEX.test(q)) return true;
  return findRelevantMedicalTopic(q) !== null;
}

export function findRelevantMedicalTopic(query: string): MedicalEncyclopediaTopic | null {
  const q = (query || '').trim().toLowerCase();
  if (!q) return null;

  let bestTopic: MedicalEncyclopediaTopic | null = null;
  let bestScore = 0;

  for (const topic of MEDICAL_ENCYCLOPEDIA_TOPICS) {
    let score = 0;
    for (const kw of topic.keywords) {
      const cleanKw = kw.trim().toLowerCase();
      if (cleanKw && q.includes(cleanKw)) {
        score += cleanKw.length >= 5 ? 4 : 2;
      }
    }
    if (q.includes(topic.title.toLowerCase())) score += 5;

    const words = q.split(/\s+/).filter((w) => w.length >= 3);
    const haystack = `${topic.title} ${topic.subtitle} ${topic.spokenConciseSummary} ${topic.keywords.join(' ')}`.toLowerCase();
    for (const w of words) {
      const stripped = w.replace(/^ال/, '');
      if (stripped.length >= 3 && haystack.includes(stripped)) {
        score += 1;
      }
    }

    if (score > bestScore) {
      bestScore = score;
      bestTopic = topic;
    }
  }

  return bestScore >= 2 ? bestTopic : null;
}

export function buildMedicalProfileSummaryText(profile?: UserMedicalProfile | null): string {
  if (!profile) return '';
  const parts: string[] = [];
  if (profile.fullName) parts.push(`الاسم: ${profile.fullName}`);
  if (profile.age) parts.push(`العمر: ${profile.age} سنة`);
  if (profile.gender) parts.push(`الجنس: ${profile.gender === 'male' ? 'ذكر' : 'أنثى'}`);
  if (profile.bloodType && profile.bloodType !== 'غير محدد') {
    parts.push(`فصيلة الدم: ${profile.bloodType}`);
  }
  if (profile.weightKg && profile.heightCm) {
    const hMeters = Number(profile.heightCm) / 100;
    const bmi =
      hMeters > 0.5 ? (Number(profile.weightKg) / (hMeters * hMeters)).toFixed(1) : '';
    parts.push(
      `الوزن: ${profile.weightKg} كغ، الطول: ${profile.heightCm} سم${bmi ? ` (مؤشر الكتلة BMI: ${bmi})` : ''}`
    );
  }
  if (profile.chronicConditions.length > 0) {
    parts.push(`الحالات الصحية المزمنة: ${profile.chronicConditions.join('، ')}`);
  }
  if (profile.allergies.length > 0) {
    parts.push(`الحساسية: ${profile.allergies.join('، ')}`);
  }
  if (profile.currentMedications.length > 0) {
    parts.push(`الأدوية الحالية: ${profile.currentMedications.join('، ')}`);
  }
  if (profile.bloodPressureBaseline) {
    parts.push(`معدل الضغط المعتاد: ${profile.bloodPressureBaseline}`);
  }
  if (profile.fastingGlucoseBaseline) {
    parts.push(`معدل السكر الصائم المعتاد: ${profile.fastingGlucoseBaseline}`);
  }
  if (profile.medicalNotes) {
    parts.push(`ملاحظات صحية: ${profile.medicalNotes}`);
  }
  return parts.join(' | ');
}

